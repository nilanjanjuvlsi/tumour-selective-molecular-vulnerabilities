# Plot helper: identify columns by common aliases, without changing the source data.
def find_col(df, aliases):
    lower = {str(c).lower().strip(): c for c in df.columns}
    for a in aliases:
        if a.lower() in lower:
            return lower[a.lower()]
    for c in df.columns:
        cl = str(c).lower().strip()
        if any(a.lower() in cl for a in aliases):
            return c
    return None

