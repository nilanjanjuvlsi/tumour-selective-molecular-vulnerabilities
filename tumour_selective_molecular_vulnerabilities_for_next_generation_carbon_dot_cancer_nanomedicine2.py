RESULTS = BASE / "02_RESULTS"

files = {
    "crispr": RAW / "CRISPR_Gene_Dependency_subsetted.csv",
    "expression": RAW / "Expression_(Short-read)_Public_26Q3_subsetted.csv",
    "mutations": RAW / "Damaging_Mutations_(Public_26Q3)_subsetted.csv",
}

report = {}
cell_line_sets = {}
gene_sets = {}

for name, path in files.items():
    print(f"\nAuditing {name}: {path.name}")

    # Read only the header first
    header = pd.read_csv(path, nrows=0)
    columns = header.columns.tolist()

    if not columns or columns[0] != "Unnamed: 0":
        print("WARNING: Unexpected first column. Inspect before proceeding.")

    genes = columns[1:]
    gene_sets[name] = set(genes)

    total_rows = 0
    ids = []
    missing_id_rows = 0

    # Read the first column only in chunks
    for chunk in pd.read_csv(
        path,
        usecols=[columns[0]],
        chunksize=50000,
        low_memory=False
    ):
        values = chunk.iloc[:, 0].astype("string")
        missing_id_rows += int(values.isna().sum())
        ids.extend(values.dropna().tolist())
        total_rows += len(chunk)

    id_series = pd.Series(ids, dtype="string")
    unique_ids = set(id_series.tolist())
    duplicate_count = int(id_series.duplicated().sum())

    cell_line_sets[name] = unique_ids

    report[name] = {
        "filename": path.name,
        "rows": total_rows,
        "columns_including_id": len(columns),
        "gene_columns": len(genes),
        "unique_cell_line_ids": len(unique_ids),
        "duplicate_id_rows": duplicate_count,
        "missing_id_rows": missing_id_rows,
        "example_ids": list(id_series.head(5)),
    }

    print("Rows:", total_rows)
    print("Gene columns:", len(genes))
    print("Unique identifiers:", len(unique_ids))
    print("Duplicate identifier rows:", duplicate_count)
    print("Missing identifier rows:", missing_id_rows)

