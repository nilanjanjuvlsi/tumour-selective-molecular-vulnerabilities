ids = sorted(set(dep.index) & set(meta.index))
dep = dep.loc[ids]
meta = meta.loc[ids]

# Focus on larger lineages for this initial inferential screen
TARGET_LINEAGES = [
    "CNS/Brain",
    "Lung",
    "Bowel",
    "Skin",
]

MIN_VALID_PER_GROUP = 20
MAX_MISSING_FRACTION = 0.05

results = []

for lineage in TARGET_LINEAGES:
    in_mask = meta["OncotreeLineage"].eq(lineage).to_numpy()
    out_mask = ~in_mask

    X_in = dep.iloc[in_mask]
    X_out = dep.iloc[out_mask]

    rows = []
    for gene in dep.columns:
        a = pd.to_numeric(X_in[gene], errors="coerce").dropna().to_numpy()
        b = pd.to_numeric(X_out[gene], errors="coerce").dropna().to_numpy()

        # Exclude genes with excessive missingness in either group
        if len(a) < MIN_VALID_PER_GROUP or len(b) < MIN_VALID_PER_GROUP:
            continue

        if len(a) < 0.95 * X_in.shape[0] or len(b) < 0.95 * X_out.shape[0]:
            continue

        if np.all(a == a[0]) and np.all(b == b[0]) and a[0] == b[0]:
            p = 1.0
        else:
            try:
                p = mannwhitneyu(
                    a, b,
                    alternative="two-sided",
                    method="asymptotic"
                ).pvalue
            except ValueError:
                p = 1.0

        rows.append({
            "lineage": lineage,
            "gene": gene,
            "n_lineage": len(a),
            "n_other": len(b),
            "median_dependency_lineage": float(np.median(a)),
            "median_dependency_other": float(np.median(b)),
            "mean_dependency_lineage": float(np.mean(a)),
            "mean_dependency_other": float(np.mean(b)),
            "median_difference": float(np.median(a) - np.median(b)),
            "fraction_ge_0_5_lineage": float(np.mean(a >= 0.5)),
            "fraction_ge_0_5_other": float(np.mean(b >= 0.5)),
            "p_value": float(p),
        })

    frame = pd.DataFrame(rows)

    if frame.empty:
        print("No genes passed quality filters for", lineage)
        continue

    frame["q_value_BH"] = multipletests(
        frame["p_value"].to_numpy(),
        method="fdr_bh"
    )[1]

    frame = frame.sort_values(
        ["q_value_BH", "median_difference"],
        ascending=[True, False]
    )
    results.append(frame)

    print("\n" + "=" * 65)
    print("LINEAGE:", lineage)
    print("Genes tested:", len(frame))
    print("Genes with BH q < 0.05:",
          int((frame["q_value_BH"] < 0.05).sum()))

    print("\nTop 10 by adjusted significance:")
    print(frame.head(10)[[
        "gene",
        "median_dependency_lineage",
        "median_dependency_other",
        "median_difference",
        "fraction_ge_0_5_lineage",
        "fraction_ge_0_5_other",
        "p_value",
        "q_value_BH",
    ]].round(5).to_string(index=False))

if results:
    combined = pd.concat(results, ignore_index=True)
    output = os.path.join(
        RESULTS, "formal_lineage_dependency_screen.csv"
    )
    combined.to_csv(output, index=False)
    print("\nSaved:", output)
else:
    print("No results generated. Check the input files and metadata.")

