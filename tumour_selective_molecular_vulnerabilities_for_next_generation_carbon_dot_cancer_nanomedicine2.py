import os
import numpy as np
import pandas as pd

BASE = "/content/drive/MyDrive/CarbonDot_Cancer"
RAW = os.path.join(BASE, "00_RAW_DATA")
PROCESSED = os.path.join(BASE, "01_PROCESSED_DATA")
RESULTS = os.path.join(BASE, "02_RESULTS")

crispr_path = os.path.join(
    RAW, "CRISPR_Gene_Dependency_subsetted.csv"
)
meta_path = os.path.join(
    PROCESSED, "three_way_matched_model_metadata.csv"
)

# Load dependency matrix and matched metadata
dep = pd.read_csv(crispr_path, low_memory=False)
dep = dep.rename(columns={dep.columns[0]: "ModelID"})
dep["ModelID"] = dep["ModelID"].astype(str)

meta = pd.read_csv(meta_path, low_memory=False)
meta["ModelID"] = meta["ModelID"].astype(str)

# Align rows explicitly by ModelID
common_ids = sorted(set(dep["ModelID"]) & set(meta["ModelID"]))
dep = dep.set_index("ModelID").loc[common_ids]
meta = meta.set_index("ModelID").loc[common_ids]

print("Aligned models:", len(common_ids))
print("Dependency features:", dep.shape[1])

# This is a provisional threshold. Confirm the exact 26Q3
# file semantics before treating this as a final dependency call.
THRESHOLD = 0.5
MIN_MODELS = 20

lineages = (
    meta["OncotreeLineage"]
    .fillna("UNANNOTATED")
    .value_counts()
)
eligible = lineages[lineages >= MIN_MODELS].index.tolist()

rows = []
for lineage in eligible:
    inside_ids = meta.index[meta["OncotreeLineage"] == lineage]
    outside_ids = meta.index[meta["OncotreeLineage"] != lineage]

    inside = dep.loc[inside_ids]
    outside = dep.loc[outside_ids]

    # Per-gene dependency prevalence, ignoring missing values
    inside_n = inside.notna().sum()
    outside_n = outside.notna().sum()

    inside_prev = (inside >= THRESHOLD).sum() / inside_n.replace(0, np.nan)
    outside_prev = (outside >= THRESHOLD).sum() / outside_n.replace(0, np.nan)

    result = pd.DataFrame({
        "gene": dep.columns,
        "lineage": lineage,
        "n_lineage_models": len(inside_ids),
        "n_other_models": len(outside_ids),
        "lineage_dependency_fraction": inside_prev.values,
        "other_dependency_fraction": outside_prev.values,
    })

    result["prevalence_difference"] = (
        result["lineage_dependency_fraction"]
        - result["other_dependency_fraction"]
    )
    rows.append(result)

screen = pd.concat(rows, ignore_index=True)

# Rank candidate lineage-enriched genes descriptively.
# This is not a significance test and not a final target ranking.
screen = screen.sort_values(
    ["lineage", "prevalence_difference"],
    ascending=[True, False]
)

out_path = os.path.join(
    RESULTS, "baseline_lineage_dependency_screen.csv"
)
screen.to_csv(out_path, index=False)

print("\nTop descriptive candidates by lineage:")
for lineage in eligible:
    sub = screen[screen["lineage"] == lineage].head(5)
    print(f"\n{lineage}")
    print(sub[
        ["gene", "n_lineage_models",
         "lineage_dependency_fraction",
         "other_dependency_fraction",
         "prevalence_difference"]
    ].round(4).to_string(index=False))

print("\nSaved:", out_path)
print(
    "\nIMPORTANT: Threshold 0.5 is provisional. "
    "Do not interpret these rankings as validated therapeutic targets."
)

